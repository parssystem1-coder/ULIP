/**
 * Dataset validation tests (Phase 17 §2, §16).
 *
 * Loads the COMMITTED dataset through the real loader so any drift breaks the
 * test suite instead of silently changing metrics.
 */
import { strict as assert } from 'node:assert';
import { test } from 'node:test';
import { aliasKey } from '@ulip/domain';
import {
  loadDefaultDataset,
  parseDataset,
  EvalDatasetError,
  expectedLabelsFor,
  canonicalLabelsFor,
} from '../src/dataset.ts';
import { EVAL_DIMENSIONS } from '../src/contracts.ts';

const dataset = loadDefaultDataset();

test('committed dataset is valid, human-labeled and complete', () => {
  assert.match(dataset.provenance, /human/i);
  assert.ok(dataset.cases.length >= 30, `expected ≥30 cases, got ${dataset.cases.length}`);
  const ids = new Set(dataset.cases.map((c) => c.caseId));
  assert.equal(ids.size, dataset.cases.length, 'caseIds must be unique');
  assert.equal(dataset.taxonomyVersion, 1);
  assert.ok(dataset.taxonomySnapshot.length >= 19);
  assert.ok(dataset.taxonomyAliases.length >= 20);
  assert.ok(dataset.locationAliases.length >= 20);
});

test('dataset covers all six business types', () => {
  const btLabels = new Set(
    dataset.taxonomySnapshot.filter((n) => n.nodeKind === 'BUSINESS_TYPE').map((n) => n.label),
  );
  for (const label of ['Wholesaler', 'Retailer', 'Service Provider', 'Manufacturer', 'Distributor', 'Professional']) {
    assert.ok(btLabels.has(label), `missing business type ${label}`);
  }
  const labeled = new Set(dataset.cases.map((c) => c.expected.businessType).filter((v): v is string => v !== null));
  for (const label of btLabels) {
    assert.ok(labeled.has(label), `no case labeled with business type ${label}`);
  }
});

test('canonical examples are present with human labels', () => {
  const hp = dataset.cases.find((c) => c.caseId === 'ev-001');
  assert.ok(hp !== undefined, 'canonical case ev-001 (HP printer parts wholesaler, Tehran) missing');
  assert.equal(hp.expected.businessType, 'Wholesaler');
  assert.equal(hp.expected.location, 'Tehran');
  assert.deepEqual(hp.expected.brand.sort(), ['Canon', 'Epson', 'HP']);
  assert.ok(hp.tags.includes('CANONICAL'));

  const salon = dataset.cases.find((c) => c.caseId === 'ev-002');
  assert.ok(salon !== undefined, 'canonical case ev-002 (Shiraz hair salon coloring/balayage) missing');
  assert.equal(salon.expected.businessType, 'Service Provider');
  assert.equal(salon.expected.location, 'Shiraz');
  assert.deepEqual([...salon.expected.specialty].sort(), ['Balayage', 'Hair Coloring']);
  assert.ok(salon.tags.includes('CANONICAL'));
});

test('dataset covers the required tag categories', () => {
  const tagSet = new Set(dataset.cases.flatMap((c) => c.tags as string[]));
  for (const tag of [
    'PERSIAN', 'ENGLISH', 'MIXED', 'ARABIC_VARIANTS', 'ZWNJ', 'AMBIGUOUS',
    'WEAK_EVIDENCE', 'STRONG_EVIDENCE', 'MISSING_LOCATION', 'INACTIVE', 'NOISY_AUDIENCE',
  ]) {
    assert.ok(tagSet.has(tag), `tag ${tag} not covered by any case`);
  }
});

test('every case has at least one expected label or an expected outcome', () => {
  for (const c of dataset.cases) {
    const labels = EVAL_DIMENSIONS.map((d) => expectedLabelsFor(c, d));
    const hasLabel = labels.some((ls) => ls.length > 0);
    const hasOutcome = c.expectedOutcome !== undefined;
    assert.ok(hasLabel || hasOutcome, `${c.caseId} has neither labels nor outcome`);
  }
});

test('expected labels only reference canonical label spaces (brands excepted)', () => {
  for (const c of dataset.cases) {
    const bt = canonicalLabelsFor(dataset, 'businessType');
    if (c.expected.businessType !== null) assert.ok(bt.has(aliasKey(c.expected.businessType)), `${c.caseId}: non-canonical businessType`);
    const ind = canonicalLabelsFor(dataset, 'industry');
    if (c.expected.industry !== null) assert.ok(ind.has(aliasKey(c.expected.industry)), `${c.caseId}: non-canonical industry`);
    const loc = canonicalLabelsFor(dataset, 'location');
    for (const l of expectedLabelsFor(c, 'location')) {
      assert.ok(loc.has(aliasKey(l)), `${c.caseId}: non-canonical location ${l}`);
    }
    const brand = canonicalLabelsFor(dataset, 'brand');
    for (const b of c.expected.brand) {
      assert.ok(brand.has(aliasKey(b)), `${c.caseId}: brand ${b} not in alias table`);
    }
  }
});

test('loader rejects non-human provenance, duplicate ids and unknown tags', () => {
  const base = JSON.parse(JSON.stringify(dataset)) as Record<string, unknown>;
  const noHuman = { ...base, provenance: 'labels generated by a model' };
  assert.throws(() => parseDataset(JSON.stringify(noHuman)), EvalDatasetError);

  const dup = JSON.parse(JSON.stringify(dataset)) as { cases: { caseId: string }[] };
  dup.cases.push({ ...dup.cases[0]!, caseId: dup.cases[0]!.caseId });
  assert.throws(() => parseDataset(JSON.stringify(dup)), /duplicate caseId/);

  const badTag = JSON.parse(JSON.stringify(dataset)) as { cases: { tags: string[] }[] };
  badTag.cases[0]!.tags = ['NOT_A_TAG'];
  assert.throws(() => parseDataset(JSON.stringify(badTag)), /unknown tag/);

  const brokenJson = '{"datasetVersion": "1.0.0",';
  assert.throws(() => parseDataset(brokenJson), EvalDatasetError);
});
